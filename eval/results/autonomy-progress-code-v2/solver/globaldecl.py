"""Declare the globals an m2c draft names but nothing defines.

After typedecl and byte-indexing, the largest surviving blocker on the leaf
residual is this, 43 of ~161 functions:

    void releaseRelocatableHeapBlockMetadata(RelocatableHeapBlock *block) {
        temp_t7 = gRelocatableHeapUsedBlockCount - 1;   <- undefined

The name is real -- it is in symbol_addrs.txt, and m2c took it from there -- so
nothing has to be invented. The join is mechanical: symbol_addrs.txt gives
name -> address, and the evidence tier keys observed accesses by
`global:0xADDRESS`. Width and signedness come from those accesses, never from
symbol_addrs.txt's own `// size:` annotations, which are the decomp team's
curation rather than a binary fact.

TWO DECLARATION SHAPES, and the difference matters for codegen:

  scalar          one observed offset, not subscripted   ->  extern u32 g;
  incomplete      subscripted, or several offsets        ->  extern u32 g[];

`extern T g[];` is a legal C89 incomplete array type. It permits subscripting,
it commits to NO extent -- which is right, because the binary does not reveal
one -- and it does not change the address the compiler emits. Guessing a bound
would be a fabricated fact; this is the "unknown is the default" rule spelled
in C.

Deliberately excluded: anything already declared in the draft, anything the
build declares, and any name used as a callee. A function's prototype is a
different problem with different codegen consequences, and getting it wrong is
a wrong call sequence rather than a compile error.
"""

from __future__ import annotations

import re

from solver import structgen, typedecl, unknowns

CALLED = re.compile(r"\b([A-Za-z_]\w*)\s*\(")
SUBSCRIPTED = re.compile(r"\b([A-Za-z_]\w*)\s*\[")
IDENTIFIER = re.compile(r"\b[A-Za-z_]\w*\b")
# `extern` and a name in the same statement, however the draft spelled it.
ALREADY_EXTERN = re.compile(r"\bextern\b[^;]*\b{}\b[^;]*;")


def declared_already(code: str, name: str) -> bool:
    return bool(re.search(ALREADY_EXTERN.pattern.format(re.escape(name)), code))


def plan(conn, code: str, func: str, known_types: set[str],
         symbols: dict[str, int]) -> list[dict]:
    """One entry per undeclared global the draft names, with evidence cited."""
    local = unknowns.declared_names(code) | {func} | known_types
    called = {m.group(1) for m in CALLED.finditer(code)}
    subscripted = {m.group(1) for m in SUBSCRIPTED.finditer(code)}
    seen: set[str] = set()
    out: list[dict] = []
    for name in IDENTIFIER.findall(code):
        if (name in seen or name in local or name in called
                or name not in symbols or declared_already(code, name)):
            continue
        seen.add(name)
        addr = symbols[name]
        slots, _loaded, _stored, cites = unknowns._global_evidence(conn, addr)
        if not slots:
            continue                       # no evidence: declare nothing
        base = min(slots, key=lambda s: s["offset"])
        ctype = structgen.field_type(base["width"], base["signed"])
        array = name in subscripted or len(slots) > 1
        out.append({
            "name": name,
            "address": addr,
            "ctype": ctype,
            "array": array,
            "offsets": [s["offset"] for s in slots],
            "cites": cites,
            "text": f"extern {ctype} {name}[];" if array
                    else f"extern {ctype} {name};",
        })
    return out


def apply(code: str, plans: list[dict]) -> str:
    if not plans:
        return code
    block = "\n".join(
        ["", "/* Widths are binary facts from the evidence tier; extents are",
         "   deliberately unspecified. Generated by solver/globaldecl.py. */"]
        + [p["text"] for p in plans] + [""])
    includes = list(typedecl.INCLUDE_LINE.finditer(code))
    at = includes[-1].end() if includes else 0
    return code[:at] + block + code[at:]


def declare(conn, code: str, func: str, known_types: set[str],
            symbols: dict[str, int]) -> tuple[str, list[dict]]:
    plans = plan(conn, code, func, known_types, symbols)
    return apply(code, plans), plans
